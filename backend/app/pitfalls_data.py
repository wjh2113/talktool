def _key(x: str) -> str:
    import re
    return re.sub(r"[\s，。、“”‘’：:！!？?（）()「」…—-]", "", x.split("→")[0])


def _similar(a: str, b: str) -> bool:
    from difflib import SequenceMatcher
    if not a or not b:
        return False
    if a in b or b in a:
        return True
    return SequenceMatcher(None, a, b).ratio() >= 0.6


def _dedupe(items):
    """去重：错误做法相同或很像的只留一条，优先留带“→ 改法”的那条。"""
    out = []
    for x in items:
        if not x:
            continue
        k = _key(x)
        hit = next((i for i, y in enumerate(out) if _similar(k, _key(y))), None)
        if hit is None:
            out.append(x)
        elif "→" in x and "→" not in out[hit]:
            out[hit] = x
    return out


def section_items(keys, field):
    return _dedupe([x for k in keys for x in SECTIONS[k][field]])


def apply_to_frameworks(frameworks: list) -> None:
    """框架误区以资料为准（+ 保留项），原则并入使用技巧；记下出处。"""
    for f in frameworks:
        keys = FW_SECTIONS.get(f["code"])
        if not keys:
            continue
        f["pitfalls"] = _dedupe(section_items(keys, "pitfalls") + FW_KEEP.get(f["code"], []))
        f["tips"] = _dedupe(list(f.get("tips") or []) + section_items(keys, "tips"))
        f["pitfall_source"] = "、".join(SECTIONS[k]["src"] for k in keys)


def drill_pitfalls(title: str, own: list) -> list:
    """训练的误区：场景自己的在前，资料话题的在后。"""
    return _dedupe(list(own or []) + section_items(DRILL_SECTIONS.get(title, []), "pitfalls"))


