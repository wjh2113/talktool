def _load_ip():
    import json
    from pathlib import Path
    data = json.loads((Path(__file__).resolve().parent / "frameworks_ip.json").read_text(encoding="utf-8"))
    by_code = {f["code"]: f for f in FRAMEWORKS}
    for code, extra in data["merge"].items():
        if code in by_code:
            by_code[code]["detail"] = extra["detail"]
            by_code[code]["tips"] = by_code[code]["tips"] + ["写成文章/口播稿时：" + " → ".join(st["name"] for st in extra["steps_writing"])]
    for f in data["frameworks"]:
        if f["code"] not in by_code:
            FRAMEWORKS.append(f)


_load_ip()

