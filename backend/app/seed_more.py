def merge_into(categories: list) -> list:
    """把 EXTRA 合并进 CATEGORIES 结构（返回新列表，不修改原数据）。"""
    import copy
    out = copy.deepcopy(categories)
    by_name = {c["name"]: c for c in out}
    for cat_name, scenarios in EXTRA.items():
        cat = by_name.get(cat_name)
        if cat is None:
            cat = {"name": cat_name, "scenarios": []}
            out.append(cat)
            by_name[cat_name] = cat
        for sc in scenarios:
            existing = next((s for s in cat["scenarios"] if s["title"] == sc["title"]), None)
            if existing:
                existing["drills"].extend(copy.deepcopy(sc["drills"]))
            else:
                cat["scenarios"].append(copy.deepcopy(sc))
    return out
